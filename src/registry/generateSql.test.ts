import { describe, expect, it } from 'vitest';
import { defaultProject } from '../mock/data';
import { generateSql } from './generateSql';

describe('generateSql', () => {
  it('MySQL：建表顺序按外键依赖，输出引擎/字符集/外键/中间表', () => {
    const sql = generateSql(defaultProject.database!, 'mysql');

    expect(sql).toContain('CREATE TABLE `users`');
    expect(sql).toContain('ENGINE=InnoDB DEFAULT CHARSET=utf8mb4');
    expect(sql).toContain(
      'CONSTRAINT `fk_orders_users` FOREIGN KEY (`user_id`) REFERENCES `users` (`id`)',
    );
    expect(sql).toContain('CREATE TABLE `orders_products`');
    // users 在 orders 之前创建，直接按顺序执行不报错
    expect(sql.indexOf('CREATE TABLE `users`')).toBeLessThan(
      sql.indexOf('CREATE TABLE `orders`'),
    );
  });

  it('PostgreSQL：自增用 IDENTITY，备注走 COMMENT ON', () => {
    const sql = generateSql(defaultProject.database!, 'postgresql');

    expect(sql).toContain('GENERATED BY DEFAULT AS IDENTITY');
    expect(sql).toContain('COMMENT ON TABLE "users" IS');
    expect(sql).toContain('NUMERIC(12, 2)');
    // PG 外键列不会自动建索引，生成器补一条
    expect(sql).toContain('CREATE INDEX "idx_orders_user_id"');
  });

  it('SQLite：自增主键必须是 INTEGER PRIMARY KEY AUTOINCREMENT', () => {
    const sql = generateSql(defaultProject.database!, 'sqlite');

    expect(sql).toMatch(/"id" INTEGER NOT NULL PRIMARY KEY AUTOINCREMENT/);
  });

  it('空库输出提示而不是空 SQL', () => {
    expect(generateSql({ tables: [], relations: [] }, 'mysql')).toContain(
      '还没有任何表',
    );
  });
});
