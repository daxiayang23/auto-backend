import type {
  DatabaseSchema,
  DbColumn,
  DbRelation,
  DbTable,
  SqlDialect,
} from '../schema/types';

/**
 * SQL 生成器：逻辑类型 → 方言映射，输入 Schema 输出可直接执行的 DDL。
 * 纯函数、无时间戳，同一份 Schema 生成的 SQL 永远一致，方便 diff 与版本化。
 */

export const SQL_DIALECT_LABELS: Record<SqlDialect, string> = {
  mysql: 'MySQL',
  postgresql: 'PostgreSQL',
  sqlite: 'SQLite',
};

const DIALECT_NAMES: Record<SqlDialect, string> = {
  mysql: 'MySQL',
  postgresql: 'PostgreSQL',
  sqlite: 'SQLite',
};

const quoteIdent = (name: string, dialect: SqlDialect): string =>
  dialect === 'mysql' ? `\`${name}\`` : `"${name}"`;

type TypeRenderer = (column: DbColumn) => string;

const DECIMAL_DEFAULT = { length: 10, scale: 2 };
const VARCHAR_DEFAULT_LENGTH = 128;

/** 逻辑类型 → 各方言物理类型 */
const TYPE_MAPPINGS: Record<SqlDialect, Record<string, TypeRenderer>> = {
  mysql: {
    int: () => 'INT',
    bigint: () => 'BIGINT',
    decimal: (c) =>
      `DECIMAL(${c.length ?? DECIMAL_DEFAULT.length}, ${c.scale ?? DECIMAL_DEFAULT.scale})`,
    varchar: (c) => `VARCHAR(${c.length ?? VARCHAR_DEFAULT_LENGTH})`,
    text: () => 'TEXT',
    boolean: () => 'TINYINT(1)',
    date: () => 'DATE',
    datetime: () => 'DATETIME',
    json: () => 'JSON',
    uuid: () => 'CHAR(36)',
  },
  postgresql: {
    int: () => 'INTEGER',
    bigint: () => 'BIGINT',
    decimal: (c) =>
      `NUMERIC(${c.length ?? DECIMAL_DEFAULT.length}, ${c.scale ?? DECIMAL_DEFAULT.scale})`,
    varchar: (c) => `VARCHAR(${c.length ?? VARCHAR_DEFAULT_LENGTH})`,
    text: () => 'TEXT',
    boolean: () => 'BOOLEAN',
    date: () => 'DATE',
    datetime: () => 'TIMESTAMP',
    json: () => 'JSONB',
    uuid: () => 'UUID',
  },
  sqlite: {
    int: () => 'INTEGER',
    bigint: () => 'INTEGER',
    decimal: (c) =>
      `NUMERIC(${c.length ?? DECIMAL_DEFAULT.length}, ${c.scale ?? DECIMAL_DEFAULT.scale})`,
    varchar: () => 'TEXT',
    text: () => 'TEXT',
    boolean: () => 'INTEGER',
    date: () => 'DATE',
    datetime: () => 'DATETIME',
    json: () => 'TEXT',
    uuid: () => 'TEXT',
  },
};

const isNumericDefault = (value: string): boolean =>
  /^-?\d+(\.\d+)?$/.test(value);

const isBooleanish = (value: string): boolean =>
  value === 'true' || value === 'false';

/** 默认值：数字 / 布尔 / CURRENT_TIMESTAMP 原样，其余按字符串加引号 */
const renderDefault = (value: string, dialect: SqlDialect): string => {
  const trimmed = value.trim();
  if (!trimmed) return '';
  if (isNumericDefault(trimmed)) return trimmed;
  if (isBooleanish(trimmed)) {
    return dialect === 'postgresql'
      ? trimmed.toUpperCase()
      : trimmed === 'true'
        ? '1'
        : '0';
  }
  if (/^CURRENT_TIMESTAMP$/i.test(trimmed)) return 'CURRENT_TIMESTAMP';
  return `'${trimmed.replace(/'/g, "''")}'`;
};

interface ColumnRender {
  definition: string;
  /** 追加在主键后面的修饰（sqlite 的 AUTOINCREMENT） */
  primaryKeySuffix?: string;
}

const renderColumn = (column: DbColumn, dialect: SqlDialect): ColumnRender => {
  const parts: string[] = [quoteIdent(column.key, dialect)];

  const isInteger = column.dbType === 'int' || column.dbType === 'bigint';

  // SQLite 的自增必须是 INTEGER PRIMARY KEY AUTOINCREMENT，类型要特判
  if (dialect === 'sqlite' && column.autoIncrement) {
    parts.push('INTEGER');
  } else {
    parts.push(TYPE_MAPPINGS[dialect][column.dbType]!(column));
  }

  if (!column.nullable) parts.push('NOT NULL');

  if (column.defaultValue) {
    const rendered = renderDefault(column.defaultValue, dialect);
    if (rendered) parts.push(`DEFAULT ${rendered}`);
  }

  if (column.autoIncrement && dialect === 'mysql') parts.push('AUTO_INCREMENT');
  if (column.autoIncrement && dialect === 'postgresql' && isInteger) {
    parts.push('GENERATED BY DEFAULT AS IDENTITY');
  }

  if (dialect === 'mysql' && column.label) {
    parts.push(`COMMENT '${column.label.replace(/'/g, "''")}'`);
  }

  return {
    definition: parts.join(' '),
    primaryKeySuffix:
      dialect === 'sqlite' && column.autoIncrement ? 'AUTOINCREMENT' : '',
  };
};

/** 建表顺序按外键依赖拓扑排序，保证直接按顺序执行不报错 */
const orderTables = (tables: DbTable[], relations: DbRelation[]): DbTable[] => {
  const byKey = new Map(tables.map((table) => [table.key, table]));
  const visited = new Set<string>();
  const ordered: DbTable[] = [];

  const visit = (key: string, path: Set<string>) => {
    if (visited.has(key) || path.has(key)) return;
    const table = byKey.get(key);
    if (!table) return;

    path.add(key);
    relations
      .filter(
        (relation) =>
          relation.fromTable === key &&
          relation.kind !== 'manyToMany' &&
          relation.fromTable !== relation.toTable,
      )
      .forEach((relation) => visit(relation.toTable, path));
    path.delete(key);

    visited.add(key);
    ordered.push(table);
  };

  tables.forEach((table) => visit(table.key, new Set()));
  // 兜底：万一有漏（异常数据），按原顺序补上
  tables.forEach((table) => {
    if (!visited.has(table.key)) ordered.push(table);
  });

  return ordered;
};

const findPrimaryKey = (table: DbTable): DbColumn | undefined =>
  table.columns.find((column) => column.primary);

const renderFkName = (
  relation: DbRelation,
  tablesByKey: Map<string, DbTable>,
): string => {
  const from = tablesByKey.get(relation.fromTable);
  const to = tablesByKey.get(relation.toTable);
  return `fk_${from?.name ?? relation.fromTable}_${to?.name ?? relation.toTable}`;
};

interface JoinTableSpec {
  name: string;
  columns: { name: string; refTable: DbTable; refColumn: DbColumn }[];
}

/** M:N 关系自动派生中间表：Schema 里不存，生成时计算（生成优先） */
const deriveJoinTables = (database: DatabaseSchema): JoinTableSpec[] => {
  const tablesByKey = new Map(
    database.tables.map((table) => [table.key, table]),
  );
  const specs: JoinTableSpec[] = [];

  database.relations
    .filter((relation) => relation.kind === 'manyToMany')
    .forEach((relation) => {
      const a = tablesByKey.get(relation.fromTable);
      const b = tablesByKey.get(relation.toTable);
      if (!a || !b || a === b) return;

      const aPk = findPrimaryKey(a);
      const bPk = findPrimaryKey(b);
      if (!aPk || !bPk) return;

      specs.push({
        name: `${a.name}_${b.name}`,
        columns: [
          {
            name: `${a.name.replace(/s$/, '')}_id`,
            refTable: a,
            refColumn: aPk,
          },
          {
            name: `${b.name.replace(/s$/, '')}_id`,
            refTable: b,
            refColumn: bPk,
          },
        ],
      });
    });

  return specs;
};

const renderCreateTable = (
  table: DbTable,
  database: DatabaseSchema,
  dialect: SqlDialect,
): string => {
  const tablesByKey = new Map(database.tables.map((item) => [item.key, item]));
  const lines: string[] = [];
  const primaryKeyColumns = table.columns.filter((column) => column.primary);

  table.columns.forEach((column) => {
    const rendered = renderColumn(column, dialect);
    lines.push(`  ${rendered.definition}`);
  });

  // 自增主键的 sqlite 特殊形态：列上带 PRIMARY KEY AUTOINCREMENT
  const inlineAutoPk =
    dialect === 'sqlite' &&
    primaryKeyColumns.length === 1 &&
    primaryKeyColumns[0]!.autoIncrement;
  if (inlineAutoPk) {
    const pk = primaryKeyColumns[0]!;
    const index = table.columns.indexOf(pk);
    lines[index] =
      `${lines[index]} PRIMARY KEY ${renderColumn(pk, dialect).primaryKeySuffix}`;
  } else if (primaryKeyColumns.length) {
    const names = primaryKeyColumns
      .map((column) => quoteIdent(column.key, dialect))
      .join(', ');
    lines.push(`  PRIMARY KEY (${names})`);
  }

  table.columns
    .filter((column) => column.unique)
    .forEach((column) => {
      lines.push(`  UNIQUE (${quoteIdent(column.key, dialect)})`);
    });

  database.relations
    .filter(
      (relation) =>
        relation.kind !== 'manyToMany' &&
        relation.fromTable === table.key &&
        relation.fromTable !== relation.toTable,
    )
    .forEach((relation) => {
      const to = tablesByKey.get(relation.toTable);
      const fkName = renderFkName(relation, tablesByKey);

      lines.push(
        `  CONSTRAINT ${quoteIdent(fkName, dialect)} FOREIGN KEY (${quoteIdent(
          relation.fromColumn,
          dialect,
        )}) REFERENCES ${quoteIdent(to?.name ?? relation.toTable, dialect)} (${quoteIdent(
          relation.toColumn,
          dialect,
        )})`,
      );
    });

  const tableOptions =
    dialect === 'mysql'
      ? ` ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci${
          table.comment ? ` COMMENT='${table.comment.replace(/'/g, "''")}'` : ''
        }`
      : '';

  return `CREATE TABLE ${quoteIdent(table.name, dialect)} (\n${lines.join(',\n')}\n)${tableOptions};`;
};

const renderIndexStatements = (
  table: DbTable,
  database: DatabaseSchema,
  dialect: SqlDialect,
): string[] => {
  const statements: string[] = [];

  table.columns
    .filter(
      (column) =>
        column.indexed &&
        !column.primary &&
        !column.unique &&
        !isFkColumn(database, table.key, column.key),
    )
    .forEach((column) => {
      statements.push(
        `CREATE INDEX ${quoteIdent(`idx_${table.name}_${column.key}`, dialect)} ON ${quoteIdent(
          table.name,
          dialect,
        )} (${quoteIdent(column.key, dialect)});`,
      );
    });

  // 外键列默认建索引（MySQL 外键自动建，PG / SQLite 不会）
  if (dialect !== 'mysql') {
    database.relations
      .filter(
        (relation) =>
          relation.kind !== 'manyToMany' && relation.fromTable === table.key,
      )
      .forEach((relation) => {
        const column = table.columns.find(
          (item) => item.key === relation.fromColumn,
        );
        if (
          !column ||
          column.primary ||
          column.unique ||
          column.indexed ||
          statements.some((item) => item.includes(`_${column.key}`))
        ) {
          return;
        }
        statements.push(
          `CREATE INDEX ${quoteIdent(`idx_${table.name}_${column.key}`, dialect)} ON ${quoteIdent(
            table.name,
            dialect,
          )} (${quoteIdent(column.key, dialect)});`,
        );
      });
  }

  return statements;
};

const isFkColumn = (
  database: DatabaseSchema,
  tableKey: string,
  columnKey: string,
): boolean =>
  database.relations.some(
    (relation) =>
      relation.kind !== 'manyToMany' &&
      relation.fromTable === tableKey &&
      relation.fromColumn === columnKey,
  );

const renderJoinTable = (spec: JoinTableSpec, dialect: SqlDialect): string => {
  const lines = spec.columns.map(
    (item) =>
      `  ${quoteIdent(item.name, dialect)} ${TYPE_MAPPINGS[dialect][item.refColumn.dbType]!(item.refColumn)} NOT NULL`,
  );

  lines.push(
    `  PRIMARY KEY (${spec.columns
      .map((item) => quoteIdent(item.name, dialect))
      .join(', ')})`,
  );

  spec.columns.forEach((item) => {
    lines.push(
      `  CONSTRAINT ${quoteIdent(`fk_${spec.name}_${item.refTable.name}`, dialect)} FOREIGN KEY (${quoteIdent(
        item.name,
        dialect,
      )}) REFERENCES ${quoteIdent(item.refTable.name, dialect)} (${quoteIdent(
        item.refColumn.key,
        dialect,
      )})`,
    );
  });

  return `CREATE TABLE ${quoteIdent(spec.name, dialect)} (\n${lines.join(',\n')}\n)${dialect === 'mysql' ? ' ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci' : ''};`;
};

/** PG / SQLite 不支持行内 COMMENT，用独立语句补 */
const renderCommentStatements = (
  table: DbTable,
  dialect: SqlDialect,
): string[] => {
  if (dialect === 'mysql') return [];

  const statements: string[] = [];
  if (dialect === 'postgresql') {
    if (table.comment) {
      statements.push(
        `COMMENT ON TABLE ${quoteIdent(table.name, dialect)} IS '${table.comment.replace(/'/g, "''")}';`,
      );
    }
    table.columns
      .filter((column) => column.label)
      .forEach((column) => {
        statements.push(
          `COMMENT ON COLUMN ${quoteIdent(table.name, dialect)}.${quoteIdent(column.key, dialect)} IS '${column.label!.replace(/'/g, "''")}';`,
        );
      });
  }

  return statements;
};

export const generateSql = (
  database: DatabaseSchema,
  dialect: SqlDialect,
): string => {
  if (!database.tables.length) {
    return `-- 当前还没有任何表，先在画布上新建一张表\n`;
  }

  const blocks: string[] = [
    `-- 由 AutoBackend 表编排生成 · ${DIALECT_NAMES[dialect]} 方言`,
    `-- 共 ${database.tables.length} 张表 · ${database.relations.length} 条关系`,
  ];

  const ordered = orderTables(database.tables, database.relations);

  ordered.forEach((table) => {
    blocks.push('');
    if (table.comment && dialect !== 'mysql') {
      blocks.push(`-- ${table.name}: ${table.comment}`);
    }
    blocks.push(renderCreateTable(table, database, dialect));
    renderIndexStatements(table, database, dialect).forEach((statement) => {
      blocks.push(statement);
    });
    renderCommentStatements(table, dialect).forEach((statement) => {
      blocks.push(statement);
    });
  });

  const joinTables = deriveJoinTables(database);
  joinTables.forEach((spec) => {
    blocks.push('');
    blocks.push(`-- 多对多中间表（自动派生）`);
    blocks.push(renderJoinTable(spec, dialect));
  });

  return `${blocks.join('\n')}\n`;
};
